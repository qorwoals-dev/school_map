async function seed() {
  console.log("Seeding schools into Supabase...");
  const { error: schoolError } = await supabase.from("schools").upsert(SCHOOLS);
  if (schoolError) {
    console.error("School seeding error:", schoolError);
  } else {
    console.log("Successfully seeded schools!");
  }

  console.log("Seeding places into Supabase...");
  const { error: placeError } = await supabase.from("places").upsert(PLACES);
  if (placeError) {
    console.error("Places seeding error:", placeError);
  } else {
    console.log("Successfully seeded places!");
  }
}

